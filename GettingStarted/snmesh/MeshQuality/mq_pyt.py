# DC check mesh quality script version 1.3 August 8, 2018
# Supports boxmethod version P-2019.03, assumes -extended option is used
#          if mesh comes from Sprocess, use "grid remesh info= 1"
# Usage: define the acceptance limits, the Silicon (semiconductor) regions to check (separated by comma), 
#        and mesh file to be used.

# Acceptance limits (set 0 for no limit)
limit_nvert=5e5
limit_deltavol=1e-4
limit_nondel=1
limit_minedge=1e-6
limit_minangle=1e-2
limit_minvolume=1e-18
limit_maxconnect=200
limit_maxlevel=0
#---------------------------------------------------------------
# Define the Silicon regions here
SiRegions = ['Silicon_1']
# Define which mesh file to use
meshfile='n@previous@'

# --------------------------------------------------------------------------------

# Script starts here. Do not change.

import os
import sys

# in case it is a hierarchical project prepend the node directory name
if os.path.isdir('../@previous@') == True:
        meshfile = '../@previous@/' + meshfile


# test if the mesh comes from snmesh or from sprocess
trymsh = meshfile+'_msh.tdr'
tryfps = meshfile+'_fps.tdr'

if os.access(trymsh, os.R_OK) == True:
	tdrfile = trymsh
	logfile  = meshfile+'_msh.log'
	print('Found a mesh generated by snmesh.')
elif os.access(tryfps, os.R_OK) == True:
	tdrfile = tryfps
	logfile  = meshfile+'_fps.out'
	print('Found a mesh generated by sprocess.')
else:
	print('No mesh found. Please check your meshfile setting.')



# create a symbolic link for the tdr file, run the boxmethod on it, then delete the link
tmptdr="n@node@_mqc"
try:
    os.remove(tmptdr+".tdr")
except OSError:
    pass
os.symlink(tdrfile, tmptdr+".tdr")
os.system("boxmethod -extended "+tmptdr+".tdr")
os.remove(tmptdr+".tdr")

bxmfile=tmptdr+"_bxm.log"

sr=0
search=0
n_non_delaunay={}
v_non_delaunay={}

with open(bxmfile,'r') as infile:
	for line in infile:
		if 'NumberOfVertices ' in line:
			s = line.split('=')
			nvert=int(s[1])
		if 'Info for semiconductor regions' in line:
			sr=1
		if 'ElementWithMinEdge' in line and sr:
			s = line.split()
			minedge = float(s[-2])
		if 'MaxFlatElement' in line and sr:
			s = line.split()
			minangle = float(s[-2])
		if 'ElementWithMinVolume' in line and sr:
			s = line.split()
			minvol = float(s[-5])
		if 'Region non-Delaunay elements' in line:
			search = 1  # Start search for region names
		if any(entry in line for entry in SiRegions) and search:
			s = line.split()
			key  = s[0]
			n_non_delaunay[key]=(int(s[5]))
			v_non_delaunay[key]=(float(s[3]))
		if 'Total' in line and search:
			search=0	# Stop search for region names


# find the number of non-delaunay elements and the deltavol for all silicon regions
maxnondel   = sum(n_non_delaunay.values())
try:
	deltavol    = max(v_non_delaunay.values())
except:
	print('Something went wrong. Could not extract non-Delaunay volumes.')

# look up for the maximum connectivity and maximum number of layers in the mesh log-file
# look up for terminated layers: if offsetting produced terminated layers you need to decrease maxlevel by 1

nlayer = {}
lregion= ''

file = logfile
print('Logfile was:',logfile)
with open(file,'r') as infile:
	for line in infile:
		if 'Max. connectivity' in line:
			s = line.split()
			maxconnect = int(s[3])
		if 'Layering region:' in line:
			s = line.split()
			lregion=s[2]
		if 'Layer :' in line and lregion in SiRegions:
			s = line.split(':')
			nlayer[lregion] = int(s[-1])
		if "Terminated layer" in line and lregion in SiRegions:
			nlayer[lregion] -= 1


fail = 0

print('DOE: nvert {x}'.format(x=nvert))
if limit_nvert > 0   and nvert > limit_nvert:
	fail = 1
	print('Maximum number of vertices exceeded.')

print('DOE: deltavol {x:6.2E}'.format(x=deltavol))
if limit_deltavol > 0 and deltavol > limit_deltavol:
	fail = 1
	print ('Maximum delta volume exceeded.')

print('DOE: nondel {x}'.format(x=maxnondel))
if limit_nondel > 0 and maxnondel > limit_nondel:
	fail = 1
	print ('Maximum number of non-Delaunay elements exceeded.')

print('DOE: minedge {x:6.2E}'.format(x=minedge))	
if limit_minedge > 0 and minedge < limit_minedge:
	fail = 1
	print('Shortest edge smaller than allowed.')

print('DOE: minangle {x:6.2E}'.format(x=minangle)) 
if limit_minangle > 0 and minangle < limit_minangle:
	fail = 1
	print('Minimum angle smaller than allowed.') 

print('DOE: minvolume {x:6.2E}'.format(x=minvol))
if limit_minvolume > 0  and minvol < limit_minvolume:
	fail = 1
	print('Minimum volume smaller than allowed.')

print('DOE: maxconnect {x}'.format(x=maxconnect))
if limit_maxconnect > 0   and maxconnect > limit_maxconnect:
	fail = 1
	print('Maximum connectivity exceeded.')

if limit_maxlevel > 0:
	maxlevel = min(nlayer.values())+1
	print('DOE: maxlevel {x}'.format(x=maxlevel))
	if maxlevel < limit_maxlevel:
		fail = 1
		print('Fewer offsetting layers built than requested.')

if fail == 0:
	print('All criteria met.')
	os.remove(tmptdr+"_bxm.tdr")

sys.exit(fail)
